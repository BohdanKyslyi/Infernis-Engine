function normal(shader, t_base, t_second, t_detail)
    shader:begin("model_scope_lense", "model_compscreen")
        :fog(false)
        :zb(true, true)
        :blend(true, blend.srcalpha, blend.invsrcalpha)
        :aref(false, 0)
        :sorting(2, true)
        :distort(false)
    shader:sampler("s_base"):texture(t_base)
end
